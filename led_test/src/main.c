/*1.理解：守护进程的"长久生命"是指一种"特权"或"身份"
	一个普通程序运行时，周期生命和终端会话时绑定的。一旦关闭或注销登录，操作系统会将这个终端所有启动的 进程杀掉。
	daemon_init()函数所做的一系列操作(fork,setsid,exit等)，实际上是让这个进程脱离了终端会话的控制。
	这个进程就有了"守护进程"的身份。操作系统将它视为一个独立的后台服务进程。不会主动杀死它"

2.程序的生命周期是什么？
	答：程序的生命周期是指从程序开始执行到结束的整个过程，包括加载、执行、暂停、恢复和终止等阶段。
	一个进程会不会杀死，除了操作系统杀死外，还取决于自身会不会"寿终正寝"
	对于一个C程序而言，当main函数执行完毕，或者调用exit()函数时，程序就会结束,进程就会正常退出(包括守护进程)。

3.为什么需要 while(1)？—— 连接“身份”与“行为”的桥梁
	通过 daemon_init() 创造了一个拥有“不死特权”的守护进程。
	但是，如果我们不给这个守护进程安排工作，它的 main() 函数从 daemon_init() 返回后，后面没有任何代码，main 函数立刻就结束了。
	根据C语言的规则，main 函数一结束，这个进程就自己正常退出了。
	所以，即使它拥有“不死特权”，它自己“自杀”了，那它的生命也就结束了。
	while(1) 循环的作用，就是给这个拥有“不死特权”的守护进程，安排一件永远也做不完的工作。这样就实现了进程的永生。

3.守护进程的生命周期是如何管理的？
	答：守护进程的生命周期通常由操作系统管理。它会在系统启动时启动，并在系统关闭时终止。
		守护进程可以通过编写代码来处理信号（如SIGHUP, SIGTERM等）以实现优雅退出。
		如果守护进程需要长时间运行，它通常会包含一个无限循环来持续执行其任务。


总结：
daemon_init() 解决了“被动死亡”（被系统杀死）的问题。
while(1) 解决了“主动死亡”（程序自己正常退出）的问题。
*/