#include <stdio.h>
#include <stdint.h>
#include <fcntl.h>
#include <unistd.h>

// CRC8生成多项式
#define POLYNOMIAL 0x07
// x ^ 8 + x ^ 2 + x ^ 1 + x ^ 0
//关于0x07的解释：
//CRC8的生成多项式是一个二进制数，表示为x^8 + x^2 + x^1 + x^0。1 0000 0111 但是多项式最高次项的幂（这里是 x^8）决定了它的阶数。
//8阶代表着产生一个8位的CRC校验码，因此最高位省略。这个多项式在二进制中表示为 00000111，


// 全局变量，初始化CRC包含256个条目的数组，用于存放CRC8查询表
uint8_t crc8_table[256];

//函数定义:初始化CRC8查询表
void init_crc8_table(void)
{
    uint32_t i, j;//声明循环计数器变量

    //外层循环:遍历0到255，为每一个可能的字节值生成一个CRC校验码
    //0000 0000 到 1111 1111  (128,64,32,16,8,4,2,1)
    for (i = 0; i < 256; i++)
    {
        //将当前要计算的字节值(i)赋给CRC变量
        uint8_t crc = i;
        
        //内层循环:对每个字节值进行8次迭代，模拟CRC的位移和异或操作
        //每次迭代相当于处理CRC的一个比特位
        for (j = 8; j > 0; j--)
        {
            //检查crc变量的最高位(MSB)是否为1
            //0x80的二进制是1000 0000 , 按位与操作(&)可以判断最高位
            if (crc & 0x80)
                //如果最高位为1，则:
                //1.将crc左移一位 (crc << 1)
                //2.将结果与生成多项式(POLYNOMIAL, 0x07)进行异或(^)运算
                crc = (crc << 1) ^ POLYNOMIAL;
            else
                //如果最高位为0，则只需将crc左移一位
                crc <<= 1;
        }
        //内层循环结束后，crc变量中存放的就是字节i对应的CRC校验码
        //将这个计算结果存入查询表的对应位置
        crc8_table[i] = crc;
    }
}

//crc8()-使用查询表快速查询计算数据的CRC8校验码
//函数定义:接收一个数据指针(data)和数据长度(len)
uint8_t crc8(const uint8_t* data, size_t len)
{
    //定义一个指针byte,指向数据的起始位置
    const uint8_t* byte = data;
    //初始化CRC寄存器，起始值通常为0x00
    uint8_t crc = 0x00;

    // 循环：逐个字节地处理传入的数据
    for (; len > 0; len--)
    {   
        // 这是整个快速CRC算法的核心步骤
        // 1. *byte++ : 获取当前指针指向的字节值，然后将指针移动到下一个字节。
        // 2. crc ^ *byte : 将上一次的CRC结果与当前字节进行异或运算。
        // 3. (...) & 0xFF : 确保异或结果是一个8位的合法数组索引(0-255)。
        // 4. crc8_table[...] : 使用这个索引去查询预先计算好的CRC表。
        // 5. crc = ... : 将查表得到的结果更新为新的CRC值。
        crc = crc8_table[(crc ^ *byte++) & 0xFF];

        /*场景设定：
            crc:这是一个8位的CRC累加器。假设它在处理上一个字节后，当前的值是0x1A
            byte:这是一个指针，正指向我们要处理的下一个数据字节。我们假设这个字节的值是 0xB5。
            crc8_table[]: 这是我们已经初始化好的，包含256个CRC“答案”的速查表。
            目标:结合当前的CRC值0x1A和当前的数据0xB5,快速计算出新的CRC值。
        从内往外分析:
            *byte++:指针后移，由使用的值是byte指针移动之前的值，也就是0xB5
            crc ^ *byte:(0x1A ^ 0xB5)
                crc (上一次的CRC结果): 0x1A -> 二进制 0001 1010
                *byte (当前处理的数据): 0xB5 -> 二进制 1011 0101
            这一步骤的目的:把“上一次的余数”和“新的数据”混合起来，生成一个用于查表的“索引”
            (0xAF) & 0xFF:防御性编程;任何一个8位数和0xFF进行"与"运算，结果都是它本身。确保索引的的值绝对只保留其低8位
            crc8_table[...];查表环节,上一步得到的索引0xAF(十进制175),就去crc8_table这个数组的第175个元素
        */
    }

    // 当所有字节都处理完毕后，crc中存放的就是整段数据的最终CRC8校验码
    return crc;
}


//CRC校验(循环冗余检验码)
/*
(N,k)码，整个编码长度为N位，其中前k位为信息位，后N-k位为校验位。
CRC校验的基本原理是将数据视为一个多项式，然后用一个预定义的多项式（生成多项式）对数据进行除法运算，得到的余数就是CRC校验码。
CRC校验的步骤如下：
    1、将X的最高次幂为R的生成多项式G(X)转换成对应的R+1位二进制数。
    2、将信息码左移R位，相当于对应的信息多项式C(X)*2R。
    3、用生成多项式（二进制数）对信息码做除，得到R位的余数(注意：这里的二进制做除法得到的余数其实是模2除(异或,相同为0,不同为1)法得到的余数，并不等于其对应十进制数做除法得到的余数。)。
    4、将余数拼到信息码左移后空出的位置，得到完整的CRC码。

例如：假设使用的生成多项式是G(X)=X3+X+1。4位的原始报文为1010，求编码后的报文。
    1、生成多项式G(X)对应的二进制数为1011。
    2、将原始报文左移3位，得到1010000。
    3、用生成多项式对1010000进行除法运算，得到余数011(余数是校验码)。
    4、将余数011拼接到原始报文后面，得到完整的CRC码1010000011。

    被除数：1010 000(补了3个0的原始报文)
    除数：1101 (生成多项式)
    余数：011 (CRC校验码)
    异或运算(相同位为0，不同位为1):
    1011 | 1010 000
           1011      <-- 这里不是真的减，而是做异或 (XOR)
           ---------
           0001      <-- (1 XOR 1=0), (0 XOR 0=0), (1 XOR 1=0), (0 XOR 1=1)
    *** 将上一步的结果 0001，从被除数后面“借”一位下来，组成新的4位数 0010。
    1011 | 1010 000
           1011
           ---------
           0001 0    <-- 从被除数借下一个 '0'
    说明:新的除数是0010.最高位是0，比除数1011小，所以商是0.相当于0010异或0000,结果还是0010.
    。。。
    一直借到除数是1000，最高位是1，现在可以和除数1011进行异或了。余数是011。

CRC校验的整个原理就是：
发方：对原始数据执行一次CRC运算（模2除法），得到一个余数（CRC码），然后把这个CRC码附在原始数据后面一起发出去。
收方：对接收到的数据中的“原始数据”部分，执行完全相同的CRC运算，得到一个“本地计算的CRC码”。
对比：比较“本地计算的CRC码”和“接收到的CRC码”。
如果两者相同，就代表数据在传输过程中有极高的概率是完好无损的。
如果两者不同，就代表数据肯定在传输中发生了错误，需要丢弃或请求重发。


*/
